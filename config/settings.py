# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
# Order: DATABASE_URL; else DB_HOST/DB_PORT/DB_NAME/DB_USER/DB_PASSWORD (prod: RDS, password
# injected from SSM by ECS); else local SQLite for development.

def _database_config():
    if env("DATABASE_URL", default=""):
        config = env.db("DATABASE_URL")
    elif env("DB_HOST", default=""):
        config = {
            "ENGINE": "django.db.backends.postgresql",
            "HOST": env("DB_HOST"),
            "PORT": env.int("DB_PORT", default=5432),
            "NAME": env("DB_NAME", default="ecg"),
            "USER": env("DB_USER", default="ecg_admin"),
            "PASSWORD": env("DB_PASSWORD", default=""),
            "OPTIONS": {"sslmode": env("DB_SSLMODE", default="require")},
        }
    else:
        return {"ENGINE": "django.db.backends.sqlite3", "NAME": BASE_DIR / "db.sqlite3"}
    config["CONN_MAX_AGE"] = 60
    config["CONN_HEALTH_CHECKS"] = True
    return config


DATABASES = {"default": _database_config()}
